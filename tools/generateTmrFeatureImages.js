const fs = require('fs');
const path = require('path');

const PROJECT_ROOT = path.resolve(__dirname, '..');

const IMAGE_ROOT = path.join(
  PROJECT_ROOT,
  'assets',
  'tmr-feature-guide'
);

const OUTPUT_FILE = path.join(
  PROJECT_ROOT,
  'src',
  'features',
  'tmrFeatureGuide',
  'data',
  'tmrFeatureImages.js'
);

const SUPPORTED_EXTENSIONS = new Set([
  '.jpg',
  '.jpeg',
  '.png',
  '.webp',
]);

const naturalSort = (a, b) =>
  a.localeCompare(b, undefined, {
    numeric: true,
    sensitivity: 'base',
  });

// Several official reference sheets apply to a family of related string codes.
// Keep one physical image set and resolve those codes to the shared source.
const FEATURE_IMAGE_SOURCES = {
  KB_: ['KB'],
  KI_: ['KB'],
  KL_: ['KB'],
  KT_: ['KB'],
  VMS_: ['VMS'],
  PPRF: ['VMS', 'PPRF'],
  BD_: ['BD'],
  BK_: ['BD'],
  BJ_: ['BD'],
  HB_: ['BD'],
  HT_: ['BD'],
  SF_: ['BD'],
};

const isSupportedImage = (fileName) => {
  const extension = path.extname(fileName).toLowerCase();

  return SUPPORTED_EXTENSIONS.has(extension);
};

const toRequirePath = (code, fileName) => {
  return `../../../../assets/tmr-feature-guide/${code}/${fileName}`;
};

const generateImageMapping = () => {
  if (!fs.existsSync(IMAGE_ROOT)) {
    throw new Error(
      `Image folder not found:\n${IMAGE_ROOT}`
    );
  }

  const codeFolders = fs
    .readdirSync(IMAGE_ROOT, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort(naturalSort);

  const featureEntries = [];
  let totalImages = 0;

  for (const codeFolder of codeFolders) {
    const fullFolderPath = path.join(
      IMAGE_ROOT,
      codeFolder
    );

    const imageFiles = fs
      .readdirSync(fullFolderPath, {
        withFileTypes: true,
      })
      .filter(
        (entry) =>
          entry.isFile() &&
          isSupportedImage(entry.name)
      )
      .map((entry) => entry.name)
      .sort(naturalSort);

    if (imageFiles.length === 0) {
      continue;
    }

    totalImages += imageFiles.length;

    const requireLines = imageFiles
      .map(
        (fileName) =>
          `    require('${toRequirePath(
            codeFolder,
            fileName
          )}'),`
      )
      .join('\n');

    featureEntries.push(
      `  ${JSON.stringify(codeFolder)}: [\n${requireLines}\n  ],`
    );
  }

  const output = `// AUTO-GENERATED FILE.
//
// Generated by:
// tools/generateTmrFeatureImages.js
//
// Do not manually edit this file.
// Add or remove images from assets/tmr-feature-guide,
// then run Generate_TMR_Feature_Images.bat.

export const TMR_FEATURE_IMAGES = {
${featureEntries.join('\n\n')}
};

const TMR_FEATURE_IMAGE_SOURCES = ${JSON.stringify(
    FEATURE_IMAGE_SOURCES,
    null,
    2
  )};

export const getTmrFeatureImages = (code) => {
  const sourceCodes = TMR_FEATURE_IMAGE_SOURCES[code] || [code];

  return sourceCodes.flatMap(
    (sourceCode) => TMR_FEATURE_IMAGES[sourceCode] || []
  );
};
`;

  const outputFolder = path.dirname(OUTPUT_FILE);

  fs.mkdirSync(outputFolder, {
    recursive: true,
  });

  fs.writeFileSync(OUTPUT_FILE, output, 'utf8');

  console.log('');
  console.log('TMR Feature Image Mapping Generated');
  console.log('===================================');
  console.log(`Code folders included: ${featureEntries.length}`);
  console.log(`Images included: ${totalImages}`);
  console.log('');
  console.log(`Output file:`);
  console.log(OUTPUT_FILE);
  console.log('');
};

try {
  generateImageMapping();
} catch (error) {
  console.error('');
  console.error('Generation failed.');
  console.error(
    error instanceof Error
      ? error.message
      : String(error)
  );
  console.error('');

  process.exitCode = 1;
}
